/* --------------------------------------------------------------- SQL-сиды */

// Ищем JSON по балансу скобок: регулярка не выдерживает вложенности и кавычек внутри текста.
const findJsonEnd = (s, start) => {
  let depth = 0;
  let inStr = false;
  let esc = false;
  for (let i = start; i < s.length; i++) {
    const c = s[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') inStr = true;
    else if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return i;
    }
  }
  return -1;
};

const patchLine = (line, level) => {
  const head = `(${level},'`;
  if (!line.startsWith(head)) throw new Error(`уровень ${level}: строка не начинается с ${head}`);
  const start = line.indexOf('{', head.length - 1);
  const end = findJsonEnd(line, start);
  if (end < 0) throw new Error(`уровень ${level}: не найден конец JSON`);
  const data = JSON.parse(line.slice(start, end + 1));
  if (!data.boss) throw new Error(`уровень ${level}: нет секции boss`);
  Object.assign(data.boss, D[level]);
  const json = JSON.stringify(data);
  // Одинарная кавычка сломала бы SQL-литерал: тексты должны быть без апострофов.
  if (json.includes("'")) throw new Error(`уровень ${level}: в тексте есть апостроф`);
  return `${line.slice(0, start)}${json}${line.slice(end + 1)}`;
};

const patchSql = (text) => {
  const lines = text.split('\n');
  let inLevel = false;
  let patched = 0;
  for (let i = 0; i < lines.length; i++) {
    // Строки вида (6,'...') есть и в других таблицах: правим только блок INSERT INTO level.
    if (/^INSERT INTO `level` VALUES/.test(lines[i])) inLevel = true;
    else if (inLevel && /^\s*(INSERT|\/\*|--)/.test(lines[i])) inLevel = false;
    if (!inLevel) continue;
    const m = /^\((\d+),'/.exec(lines[i]);
    if (m && D[m[1]]) {
      lines[i] = patchLine(lines[i], m[1]);
      patched++;
    }
  }
  if (patched !== 4) throw new Error(`пропатчено ${patched} строк вместо 4`);
  return lines.join('\n');
};

