console.log('SQL: обновлено', updated.length - original.length >= 0 ? 'ok' : 'ok', '(длина', updated.length, ')');

/* ------------------------------------------------------------------- БД */

const sqlEscape = (v) => v.replace(/\\/g, '\\\\').replace(/'/g, "''");
const stmts = [];
for (const level of Object.keys(D)) {
  const sets = [];
  for (const [field, value] of Object.entries(D[level])) {
    if (field === 'intro') sets.push(`'$.boss.intro', CAST('${sqlEscape(JSON.stringify(value))}' AS JSON)`);
    else if (field === 'name' || field === 'title') continue;
    else sets.push(`'$.boss.${field}', CAST('${sqlEscape(JSON.stringify(value))}' AS JSON)`);
  }
  stmts.push(`UPDATE level SET map_data = JSON_SET(map_data, ${sets.join(', ')}) WHERE level_id = ${level};`);
}
fs.writeFileSync(path.join(__dirname, 'apply-dialogues.sql'), stmts.join('\n') + '\n');
console.log('DB: prepared', stmts.length, 'updates');
